function formatDate(index: number): string {
  const months = ['Januari', 'Februari', 'Maret', 'April', 'Mei', 'Juni',
    'Juli', 'Agustus', 'September', 'Oktober', 'November', 'Desember'];
  const year = 2025 + Math.floor(index / 200);
  const month = months[Math.floor((index % 12))];
  const day = ((index % 28) + 1).toString().padStart(2, '0');
  return `${day} ${month} ${year}`;
}

function shuffleArray<T>(arr: T[]): T[] {
  const result = [...arr];
  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor((i * 9301 + 49297) % 233280) % (i + 1);
    [result[i], result[j]] = [result[j], result[i]];
  }
  return result;
}

export function generateDataset(): RawTweet[] {
  const allTemplates = [
    ...positiveTemplates.map((t) => ({ text: t, type: 'pos' as const })),
    ...negativeTemplates.map((t) => ({ text: t, type: 'neg' as const })),
    ...neutralTemplates.map((t) => ({ text: t, type: 'neu' as const })),
  ];

  const shuffled = shuffleArray(allTemplates);
  const total = shuffled.length;

  // Expand to 400 records by cycling through with slight modifications
  const dataset: RawTweet[] = [];
  for (let i = 0; i < 400; i++) {
    const template = shuffled[i % total];
    // Add slight variation for duplicates by appending subtle context
    let text = template.text;
    if (i >= total) {
      const suffixes = [
        ' #banjirsumatera', ' #bencana', ' #prayforsumatera', ' #banjirbandang',
        ' https://bit.ly/info', ' @info_banjir', ' #sumatera', ' #bpbd',
      ];
      text = template.text + suffixes[i % suffixes.length];
    }

    const label = lexiconLabel(text);
    const username = usernames[i % usernames.length];

    dataset.push({
      id: `TW-${(i + 1).toString().padStart(4, '0')}`,
      tanggal: formatDate(i),
      username,
      isiTweet: text,
      cleanedTweet: text, // Will be computed via preprocessing in context
      label,
    });
  }

  return dataset;
}

